// use this class to describe your NPC for FPGA
class Npc extends ExtModule {
    val clock = IO(Input(Clock()))
    val reset = IO(Input(Bool()))
    val io = IO(new Bundle {
        val ifu = Flipped(new InstrInterface)
        val lsu = Flipped(new DataInterface)
    })
}

// use this class to wrap your NPC info a standard interface
class FpgaCpuCore extends Module {
    val io = IO(new Bundle {
        val ifu = Flipped(new InstrInterface)
        val lsu = Flipped(new DataInterface)
    })

    val npc = Module(new Npc)
    npc.clock := clock
    npc.reset := reset
    npc.io <> io
}

