/*
 * Clock and reset for running on FPGA.
 * Modify these classes to suit your design.
 */

// This generates clock used by the SoC from the clock source of the board
// replace with what suits your board
class GowinRPll extends ExtModule {
    val clkin  = IO(Input(Clock()))
    val clkout = IO(Output(Clock()))
}

// This generates sync active high reset for the SoC from the reset of the board
// replace with what suits your board
class GowinReset extends ExtModule {
    val clock = IO(Input(Clock()))
    val reset = IO(Input(Reset()))
    val resetOut = IO(Output(Bool()))
}

/*
 * Use this class to wrap the clock and reset unit into a standard interface.
 * Note that the reset of `FpgaTop` can be active high or active low, depending
 * on the specific board you are using.
 * But the `resetOut` of this module must output an active high reset signal.
 */
class FpgaRcu extends Module {
    val io = IO(new Bundle {
        val clockOut = Output(Clock())
        val resetOut = Output(Bool())
    })

    val pll = Module(new GowinRPll)
    val gowinReset = Module(new GowinReset)

    pll.clkin := clock
    io.clockOut := pll.clkout
    // sync reset generation should be in the same clock domian with SoC
    // or it will cause problems, or at least confuse the toolchain
    gowinReset.clock := pll.clkout
    gowinReset.reset := reset
    io.resetOut := gowinReset.resetOut
}

/*
 * Memory modules for running on FPGA.
 * Modify the four following classes to suit your design.
 */

// use this class to describe the ROM generated by FPGA IP generator
class GowinPRom extends ExtModule {
    val clk = IO(Input(Clock()))
    val reset = IO(Input(Bool()))
    val ce  = IO(Input(Bool()))
    val oce = IO(Input(Bool()))
    val ad  = IO(Input(UInt(13.W)))
    val dout = IO(Output(UInt(32.W)))
}

// use this class to describe the RAM generated by FPGA IP generator
class GowinSP extends ExtModule {
    val clk = IO(Input(Clock()))
    val reset = IO(Input(Bool()))
    val ce  = IO(Input(Bool()))
    val oce = IO(Input(Bool()))
    val wre = IO(Input(Bool()))
    val ad  = IO(Input(UInt(14.W)))
    val din = IO(Input(UInt(32.W)))
    val dout = IO(Output(UInt(32.W)))
}

// use this class to wrap the ROM into a standard interface
class FpgaRom extends Module {
    val io = IO(new RomInterface)

    val rom = Module(new GowinPRom)

    rom.clk := clock
    rom.reset := reset
    rom.ce := io.ren
    rom.oce := true.B
    rom.ad := io.addr(14, 2)
    io.rdata := rom.dout
}

// use this class to wrap the RAM into a standard interface
class FpgaRam extends Module {
    val io = IO(new SramInterface)

    val ram = Module(new GowinSP)

    ram.clk := clock
    ram.reset := reset
    ram.ce := io.ren || io.wen
    ram.oce := true.B
    ram.wre := io.wen
    ram.ad := io.addr(15, 2)
    ram.din := io.wdata
    io.rdata := ram.dout
}

/* Memory modules for running on simulation. */

class SimulatedMem extends ExtModule {
    val clock = IO(Input(Clock()))
    val io = IO(new SramInterface)
}

class SimulatedRom extends Module {
    val io = IO(new RomInterface)

    val mem = Module(new SimulatedMem)
    mem.clock := clock
    mem.io.addr := io.addr
    mem.io.ren := io.ren
    io.rdata := mem.io.rdata
    mem.io.wen := false.B
    mem.io.wdata := 0.U(32.W)
}

class SimulatedSram extends Module {
    val io = IO(new SramInterface)

    val mem = Module(new SimulatedMem)
    mem.clock := clock
    mem.io <> io
}
